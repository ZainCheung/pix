import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url))
const websiteDirectory = path.resolve(scriptDirectory, '..')
const repositoryDirectory = path.resolve(websiteDirectory, '..')
const sourceDirectory = path.join(websiteDirectory, 'src')
const updatesDirectory = path.join(websiteDirectory, 'content', 'updates')
const outputPath = path.join(sourceDirectory, 'generated', 'sitemap-lastmod.ts')

const DATE_PATTERN = /^\d{4}-\d{2}-\d{2}$/

const STATIC_SOURCES = {
  '/': [
    'website/src/routes/index.tsx',
    'website/src/components/header.tsx',
    'website/src/components/footer.tsx',
    'website/src/components/hero.tsx',
    'website/src/components/product-preview.tsx',
    'website/src/components/features.tsx',
    'website/src/components/download.tsx',
    'website/src/components/faq.tsx',
    'website/src/lib/seo.ts',
  ],
  '/use-cases': [
    'website/src/routes/use-cases/index.tsx',
    'website/src/components/use-case-page.tsx',
  ],
  '/use-cases/pi-from-iphone': [
    'website/src/components/use-case-page.tsx',
    'website/src/routes/use-cases/pi-from-iphone.tsx',
  ],
  '/use-cases/remote-pi': [
    'website/src/components/use-case-page.tsx',
    'website/src/routes/use-cases/remote-pi.tsx',
  ],
  '/use-cases/continue-pi-sessions': [
    'website/src/components/use-case-page.tsx',
    'website/src/routes/use-cases/continue-pi-sessions.tsx',
  ],
  '/use-cases/local-first-ai-coding': [
    'website/src/components/use-case-page.tsx',
    'website/src/routes/use-cases/local-first-ai-coding.tsx',
  ],
  '/updates': [
    'website/src/lib/updates.ts',
    'website/src/routes/updates/index.tsx',
  ],
}

function readDocsFiles() {
  const sourcePath = path.join(sourceDirectory, 'lib', 'source.ts')
  const source = readFileSync(sourcePath, 'utf8')
  const files = [...source.matchAll(/'([^']+\.md)'/g)].map((match) => match[1])

  if (files.length === 0) {
    throw new Error(`No docs files found in ${sourcePath}`)
  }

  return files
}

function docsUrl(file) {
  const withoutExtension = file.replace(/\.md$/i, '')
  const normalized = withoutExtension
    .split('/')
    .map((segment) => segment.toLowerCase().replaceAll('_', '-'))
    .join('/')

  return normalized === 'index' ? '/docs' : `/docs/${normalized}`
}

function readUpdateFiles() {
  return readdirSync(updatesDirectory)
    .filter((file) => file.endsWith('.mdx'))
    .sort()
}

function gitDate(relativePath) {
  try {
    const date = execFileSync(
      'git',
      ['-C', repositoryDirectory, 'log', '-1', '--format=%cs', '--', relativePath],
      { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] },
    ).trim()

    return DATE_PATTERN.test(date) ? date : null
  } catch {
    return null
  }
}

function fileDate(relativePath) {
  const absolutePath = path.join(repositoryDirectory, relativePath)
  return statSync(absolutePath).mtime.toISOString().slice(0, 10)
}

function sourceDate(relativePaths) {
  const dates = relativePaths.map((relativePath) => gitDate(relativePath) ?? fileDate(relativePath))
  const validDates = dates.filter((date) => DATE_PATTERN.test(date))

  if (validDates.length === 0) {
    throw new Error(`Unable to determine a valid lastmod date for ${relativePaths.join(', ')}`)
  }

  return validDates.sort().at(-1)
}

function buildEntries() {
  const updateFiles = readUpdateFiles()
  const entries = new Map(
    Object.entries(STATIC_SOURCES).map(([url, sources]) => {
      if (url === '/updates') {
        return [
          url,
          sourceDate([
            ...sources,
            ...updateFiles.map((file) => `website/content/updates/${file}`),
          ]),
        ]
      }

      return [url, sourceDate(sources)]
    }),
  )

  for (const file of readDocsFiles()) {
    entries.set(docsUrl(file), sourceDate([`docs/${file}`]))
  }

  for (const file of updateFiles) {
    const slug = file.replace(/\.mdx$/i, '')
    entries.set(
      `/updates/${slug}`,
      sourceDate([
        `website/content/updates/${file}`,
        'website/src/routes/updates/$slug.tsx',
      ]),
    )
  }

  return Object.fromEntries([...entries].sort(([left], [right]) => left.localeCompare(right)))
}

function generatedModule(entries) {
  return `// Generated by scripts/generate-sitemap-lastmod.mjs. Do not edit manually.\n\nexport const SITEMAP_LASTMOD: Record<string, string> = ${JSON.stringify(entries, null, 2)}\n`
}

const entries = buildEntries()
mkdirSync(path.dirname(outputPath), { recursive: true })
writeFileSync(outputPath, generatedModule(entries))
console.log(`Generated ${Object.keys(entries).length} sitemap lastmod entries at ${path.relative(websiteDirectory, outputPath)}`)
